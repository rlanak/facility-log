def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # icon is always written as None here — the 3rd tuple element above is
    # just a historical note, never a verified file. download_foxhole_icons.py
    # is the only script that resolves + downloads a real file and patches
    # a verified "/assets/foxhole/..." path in; run it after this one.
    resources_json = {
        key: {
            "name": {"en": name_en, "pt": None},
            "farmable": farmable,
            "icon": None,
        }
        for key, (name_en, farmable, icon_hint) in RESOURCES.items()
    }
    (OUT_DIR / "resources.json").write_text(
        json.dumps(resources_json, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    (OUT_DIR / "building_types.json").write_text(
        json.dumps(BUILDING_TYPES, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    recipe_count = sum(len(b["recipes"]) for b in BUILDING_TYPES.values())
    print(f"{len(RESOURCES)} resources, {len(BUILDING_TYPES)} building types, {recipe_count} recipes written.")


if __name__ == "__main__":
    main()
